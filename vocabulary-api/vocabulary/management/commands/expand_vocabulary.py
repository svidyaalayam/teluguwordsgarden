class Command(BaseCommand):
    help = "Expands the Telugu vocabulary database with hundreds of curated 2-letter, 3-letter, and thematic words."

    def handle(self, *args, **options):
        level, _ = LearningLevel.objects.get_or_create(
            name="స్థాయి 1 (Primary Telugu)",
            defaults={"min_age": 5, "max_age": 12, "description": "Primary Telugu Word Garden"},
        )

        categories_cache = {}
        created_count = 0
        updated_count = 0

        with transaction.atomic():
            for term, meaning, category_name, ex_te, ex_en in DATASET:
                if category_name not in categories_cache:
                    cat, _ = VocabularyCategory.objects.get_or_create(
                        name=category_name,
                        defaults={"active": True},
                    )
                    categories_cache[category_name] = cat
                category = categories_cache[category_name]

                definition = f"{meaning} • {term} means {meaning.lower()}."
                example_sentence = f"{ex_te} • {ex_en}"

                word, created = Word.objects.update_or_create(
                    term=term,
                    defaults={
                        "definition": definition,
                        "part_of_speech": "నామవాచకం • Noun",
                        "pronunciation": term,
                        "example_sentence": example_sentence,
                        "active": True,
                    },
                )
                word.categories.add(category)
                word.levels.add(level)

                if created:
                    created_count += 1
                else:
                    updated_count += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Expanded vocabulary successfully!\n"
                f"• Created: {created_count} new words\n"
                f"• Updated: {updated_count} existing words\n"
                f"• Total words now in DB: {Word.objects.count()}\n"
                f"• Active categories: {VocabularyCategory.objects.count()}"
            )
        )
